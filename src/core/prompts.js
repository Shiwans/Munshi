// Tool declarations, system prompt and every trader-facing string, per language.

export const LANGS = ['hinglish', 'hi', 'mr', 'gu', 'en'];
export const LANG_NAMES = {
  hinglish: 'Hinglish (Hindi in Roman script)',
  hi: 'Hindi (Devanagari)',
  mr: 'Marathi (Devanagari)',
  gu: 'Gujarati (Gujarati script)',
  en: 'simple English',
};
export function parseLang(s) {
  const t = String(s || '').toLowerCase().trim();
  if (/^(hinglish|roman)/.test(t)) return 'hinglish';
  if (/^(hi|hindi|हिंदी|हिन्दी)$/.test(t)) return 'hi';
  if (/^(mr|marathi|मराठी)$/.test(t)) return 'mr';
  if (/^(gu|gujarati|ગુજરાતી)$/.test(t)) return 'gu';
  if (/^(en|english|angrezi)$/.test(t)) return 'en';
  return null;
}

